-- Task 6: Stored procedure for student check-out
CREATE OR REPLACE PROCEDURE check_out(p_allocation_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_room_id integer;
BEGIN
    SELECT room_id INTO v_room_id
    FROM allocations WHERE allocation_id = p_allocation_id AND status = 'ALLOCATED' FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active allocation with ID %', p_allocation_id;
        RETURN;
    END IF;

    UPDATE allocations SET status = 'COMPLETED' WHERE allocation_id = p_allocation_id;
    UPDATE hostel_rooms SET available_spaces = available_spaces + 1 WHERE room_id = v_room_id;

    RAISE NOTICE 'Allocation % checked out; space freed in room %', p_allocation_id, v_room_id;
END;
$$;

CALL check_out(1);
CALL check_out(1);

-- Task 7: Explicit cursor for nearly full rooms
DO $$
DECLARE
    v_rec RECORD;
    c_rooms CURSOR FOR
        SELECT room_number, available_spaces FROM hostel_rooms WHERE available_spaces <= 1 ORDER BY room_id;
BEGIN
    OPEN c_rooms;
    LOOP
        FETCH c_rooms INTO v_rec;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full/Nearly full room: % (% spaces left)', v_rec.room_number, v_rec.available_spaces;
    END LOOP;
    CLOSE c_rooms;
END;
$$ LANGUAGE plpgsql;

