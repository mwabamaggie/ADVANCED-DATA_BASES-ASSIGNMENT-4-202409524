DROP SCHEMA IF EXISTS student_hostel_room_allocation CASCADE;
CREATE SCHEMA student_hostel_room_allocation;
SET search_path TO student_hostel_room_allocation, public;

-- Task 1: Create tables and insert initial records
CREATE TABLE hostel_rooms (
    room_id integer PRIMARY KEY,
    room_number text NOT NULL,
    available_spaces integer NOT NULL CHECK (available_spaces >= 0)
);

CREATE TABLE allocations (
    allocation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id integer NOT NULL REFERENCES hostel_rooms(room_id),
    student_number text NOT NULL CHECK (length(trim(student_number)) > 0),
    status text NOT NULL CHECK (status IN ('ALLOCATED', 'COMPLETED'))
);

