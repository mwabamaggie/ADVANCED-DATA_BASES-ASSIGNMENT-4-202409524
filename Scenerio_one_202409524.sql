-- Task 7: Explicit cursor for low stock reporting
DO $$
DECLARE
    v_rec RECORD;
    c_low CURSOR FOR
        SELECT title, available_copies FROM books WHERE available_copies <= 2 ORDER BY book_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_rec;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low stock book: % (% copies remaining)', v_rec.title, v_rec.available_copies;
    END LOOP;
    CLOSE c_low;
END;
$$ LANGUAGE plpgsql;

