-- Task 6: Stored procedure for cancelling reservations
CREATE OR REPLACE PROCEDURE cancel_reservation(p_reservation_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_session_id integer;
    v_count integer;
BEGIN
    SELECT session_id, workstations_reserved INTO v_session_id, v_count
    FROM reservations WHERE reservation_id = p_reservation_id AND status = 'RESERVED' FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active reservation with ID %', p_reservation_id;
        RETURN;
    END IF;

    UPDATE reservations SET status = 'CANCELLED' WHERE reservation_id = p_reservation_id;
    UPDATE lab_sessions SET available_workstations = available_workstations + v_count WHERE session_id = v_session_id;

    RAISE NOTICE 'Reservation % cancelled; % workstations released', p_reservation_id, v_count;
END;
$$;

