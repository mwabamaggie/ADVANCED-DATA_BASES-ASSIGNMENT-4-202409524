-- Task 1: Create tables and insert initial records
CREATE TABLE lab_sessions (
    session_id integer PRIMARY KEY,
    session_name text NOT NULL,
    available_workstations integer NOT NULL CHECK (available_workstations >= 0)
);

CREATE TABLE reservations (
    reservation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id integer NOT NULL REFERENCES lab_sessions(session_id),
    lecturer_name text NOT NULL,
    workstations_reserved integer NOT NULL CHECK (workstations_reserved > 0),
    status text NOT NULL CHECK (status IN ('RESERVED', 'CANCELLED'))
);

