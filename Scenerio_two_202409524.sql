-- Task 2: IF ELSIF ELSE decision control structure
DO $$
DECLARE
    v_available integer;
BEGIN
    SELECT available_workstations INTO v_available FROM lab_sessions WHERE session_id = 2;
    IF v_available = 0 THEN
        RAISE NOTICE 'Session is full';
    ELSIF v_available <= 5 THEN
        RAISE NOTICE 'Session is nearly full: % workstations left', v_available;
    ELSE
        RAISE NOTICE 'Session has enough workstations: % available', v_available;
    END IF;
END;
$$ LANGUAGE plpgsql;

-- Task 3: WHILE loop and numeric FOR loop
DO $$
DECLARE
    v_rem integer := 1;
BEGIN
    WHILE v_rem <= 3 LOOP
        RAISE NOTICE 'Preparation reminder %', v_rem;
        v_rem := v_rem + 1;
    END LOOP;

    FOR v_chk IN 1..3 LOOP
        RAISE NOTICE 'Workstation check number %', v_chk;
    END LOOP;
END;
$$ LANGUAGE plpgsql;

-- Task 4: Stored procedure for reserving workstations
CREATE OR REPLACE PROCEDURE reserve_workstations(
    p_session_id integer,
    p_lecturer text,
    p_workstations integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available integer;
    v_res_id integer;
BEGIN
    IF p_workstations <= 0 THEN
        RAISE EXCEPTION 'Workstations requested must be positive' USING ERRCODE = '22023';
    END IF;

    SELECT available_workstations INTO v_available
    FROM lab_sessions WHERE session_id = p_session_id FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'Session % does not exist', p_session_id;
        RETURN;
    ELSIF v_available < p_workstations THEN
        RAISE NOTICE 'Exceeds capacity: only % workstations available', v_available;
        RETURN;
    END IF;

    UPDATE lab_sessions SET available_workstations = available_workstations - p_workstations WHERE session_id = p_session_id;

    INSERT INTO reservations (session_id, lecturer_name, workstations_reserved, status)
    VALUES (p_session_id, p_lecturer, p_workstations, 'RESERVED')
    RETURNING reservation_id INTO v_res_id;

    RAISE NOTICE 'Reservation % recorded for Lecturer %', v_res_id, p_lecturer;
END;
$$;

