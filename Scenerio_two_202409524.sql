-- Task 7: Explicit cursor for low capacity sessions
DO $$
DECLARE
    v_rec RECORD;
    c_low CURSOR FOR
        SELECT session_name, available_workstations FROM lab_sessions WHERE available_workstations <= 5 ORDER BY session_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_rec;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low availability: % (% workstations remaining)', v_rec.session_name, v_rec.available_workstations;
    END LOOP;
    CLOSE c_low;
END;
$$ LANGUAGE plpgsql;

