-- Task 2: IF ELSIF ELSE decision control structure
DO $$
DECLARE
    v_stock integer;
BEGIN
    SELECT stock_quantity INTO v_stock FROM medicines WHERE medicine_id = 2;
    IF v_stock = 0 THEN
        RAISE NOTICE 'Medicine is out of stock';
    ELSIF v_stock <= 10 THEN
        RAISE NOTICE 'Medicine low on stock: % remaining', v_stock;
    ELSE
        RAISE NOTICE 'Medicine sufficiently stocked: % remaining', v_stock;
    END IF;
END;
$$ LANGUAGE plpgsql;

-- Task 3: WHILE loop and numeric FOR loop
