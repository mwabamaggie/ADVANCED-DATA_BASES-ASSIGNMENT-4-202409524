-- Task 6: Stored procedure for reversing medicine dispensing
CREATE OR REPLACE PROCEDURE reverse_dispensing(p_record_id integer)
LANGUAGE plpgsql
AS $$
DECLARE 
    v_med_id integer;
    v_qty integer;
BEGIN
    SELECT medicine_id, quantity INTO v_med_id, v_qty
    FROM dispensing_records WHERE record_id = p_record_id AND status = 'DISPENSED' FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active dispensing record with ID %', p_record_id;
        RETURN;
    END IF;

    UPDATE dispensing_records SET status = 'REVERSED' WHERE record_id = p_record_id;
    UPDATE medicines SET stock_quantity = stock_quantity + v_qty WHERE medicine_id = v_med_id;

    RAISE NOTICE 'Record % reversed; % units restored', p_record_id, v_qty;
END;
$$;

CALL reverse_dispensing(1);
CALL reverse_dispensing(1);

-- Task 7: Explicit cursor for low stock medicines
DO $$
DECLARE
    v_rec RECORD;
    c_low CURSOR FOR
        SELECT medicine_name, stock_quantity FROM medicines WHERE stock_quantity <= 10 ORDER BY medicine_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_rec;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low stock medicine: % (% units left)', v_rec.medicine_name, v_rec.stock_quantity;
    END LOOP;
    CLOSE c_low;
END;
$$ LANGUAGE plpgsql;

